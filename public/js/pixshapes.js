// Una forma como imagen SVG (data:) de 16×16 con un color por cada nivel (de 1, el borde, a 4, el centro), con los
// píxeles nítidos: para usarla de fondo y escalarla con image-rendering: pixelated
export function shapeSvg(name, pal) {
  let r = '';
  (SHAPES[name] || MENU_ONLY[name]).forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== '.') r += `<rect x="${x}" y="${y}" width="1" height="1" fill="${pal[+ch - 1]}"/>`; }));
  // (entre comillas simples: va dentro de un atributo style="…")
  return `url('data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">${r}</svg>`)}')`;
}
